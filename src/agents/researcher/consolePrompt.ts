export interface TopicContext {
  title: string;
  brief?: string | null;
}

// Claude.aiのコンソールに人間が直接コピー&ペーストして実行するためのプロンプト。
// API経由のweb_search/web_fetchツールは使えないため、Claude自身の知識や
// コンソール側のWeb検索機能(有効な場合)を使って調べてもらい、結果はJSONで受け取る。
export function buildResearcherConsolePrompt(topic: TopicContext): string {
  return `あなたは恋愛メディアの記事制作チームに所属する「調査員」です。
この会話でのあなたの仕事は、次の依頼についてWeb上の情報を調べ、ライターが記事執筆に
そのまま使える形に整理して報告することだけです。記事の執筆や企画立案は行いません。

# 調査テーマ

${topic.title}
${topic.brief ? `\n# 依頼内容\n\n${topic.brief}\n` : ""}
# 調査の進め方

1. Web検索機能が使える場合はそれを使い、使えない場合はあなたの知識の範囲で、
   信頼できる情報源を探してください。
2. 情報源ごとに、要約・重要ポイント・（あれば）引用・信頼度/関連度の評価・タグを整理する。
   要約は元記事の丸写しではなく、あなた自身の言葉でまとめること。
3. 実際に確認していない情報（URL・数値・引用文など）をでっち上げないこと。確信が持てない
   情報は登録しないか、notesにその旨を記載すること。
4. 目安として3〜8件程度、異なる角度（統計データ／専門家の見解／実際の利用者の声／
   競合の傾向 など）をカバーするように集めること。

# 信頼度（reliability）の基準

- 5: 公的機関・大手ニュースメディア・大手サービス運営元の公式発表や統計
- 4: 業界専門メディア・調査会社のレポート・有識者への取材記事
- 3: 出典が明記された一般的なWebメディアや企業ブログ
- 2: 個人ブログ・SNS投稿・裏付けの弱い体験談
- 1: 出典不明、広告目的が強い、信頼性に疑問がある情報

# 関連度（relevance）の基準

- 5: 依頼内容に直接答える一次情報や統計
- 4: 依頼内容に強く関連する具体的なデータやエピソード
- 3: 背景情報として有用だが直接的ではない
- 2: 周辺情報程度の関連性
- 1: ほぼ無関係（基本的には登録しない）

# 回答形式（重要）

説明や前置きの文章は書かず、下記の形式のJSONオブジェクトを \`\`\`json ... \`\`\` の
コードブロック1つだけで出力してください。コードブロックの外には何も書かないでください。
summary/keyPoints/tags/notesはすべて日本語で書いてください。

\`\`\`json
{
  "items": [
    {
      "url": "https://...(実際に確認した情報源のURL)",
      "sourceTitle": "情報源ページのタイトル(任意)",
      "author": "著者名(任意)",
      "siteName": "サイト名(任意)",
      "summary": "日本語での要約(2〜4文)",
      "keyPoints": ["重要ポイント1", "重要ポイント2"],
      "quotes": [{ "text": "引用文", "context": "誰の発言か等(任意)" }],
      "reliability": 3,
      "relevance": 3,
      "tags": ["タグ1", "タグ2"],
      "notes": "補足(任意)"
    }
  ]
}
\`\`\``;
}
